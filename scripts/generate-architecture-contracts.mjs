#!/usr/bin/env node

import fs from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();
const OUT_DIR = path.join(ROOT, 'doc', 'architecture');

const read = (relativePath) => fs.readFileSync(path.join(ROOT, relativePath), 'utf8');
const list = (relativeDir, suffix) => fs.readdirSync(path.join(ROOT, relativeDir))
  .filter((file) => file.endsWith(suffix))
  .sort()
  .map((file) => path.join(relativeDir, file));

function walk(relativeDir, suffixes) {
  const absoluteDir = path.join(ROOT, relativeDir);
  if (!fs.existsSync(absoluteDir)) return [];
  const entries = fs.readdirSync(absoluteDir, { withFileTypes: true });
  return entries.flatMap((entry) => {
    const relativePath = path.join(relativeDir, entry.name);
    if (entry.isDirectory()) return walk(relativePath, suffixes);
    return suffixes.some((suffix) => entry.name.endsWith(suffix)) ? [relativePath] : [];
  }).sort();
}

const sensitiveEnvOrColumnPattern = /(^|_)(access|refresh|private|secret|secrets|password|passwd|pass|token|credential|encryption|encrypted|salt)(_|$)|(_api_key|_api_secret|_token|_secret|_password|_key|_hash)$/i;

function isSensitiveIdentifier(name) {
  return sensitiveEnvOrColumnPattern.test(name) || /DATABASE_URL|REDIS_URL|SMTP_PASS|DB_PASS|PGPASSWORD|JWT_SECRET|WEBHOOK_URL|LOGIN/i.test(name);
}

function ensureOutDir() {
  fs.mkdirSync(OUT_DIR, { recursive: true });
}

function table(headers, rows) {
  return [
    `| ${headers.join(' | ')} |`,
    `| ${headers.map(() => '---').join(' | ')} |`,
    ...rows.map((row) => `| ${row.map((cell) => String(cell ?? '').replaceAll('\n', '<br>').replaceAll('|', '\\|')).join(' | ')} |`),
  ].join('\n');
}

function writeDoc(fileName, title, sections) {
  const content = [
    `# ${title}`,
    '',
    'Generated by `npm run inventory:architecture` from source files. Do not hand-edit generated tables without updating the generator.',
    '',
    ...sections,
    '',
  ].join('\n');
  fs.writeFileSync(path.join(OUT_DIR, fileName), content);
}

function routeMounts() {
  const source = read('backend/index.ts');
  const rows = [];
  const usePattern = /app\.use\(\s*['`]([^'`]+)['`]\s*,\s*([^\n;]+)\);/g;
  for (const match of source.matchAll(usePattern)) {
    const mount = match[1];
    const handlers = match[2].trim();
    const auth = handlers.includes('authenticate') || handlers.includes('createDeviceRoutes') ? 'mounted-auth' : 'route-owned/unknown';
    rows.push([mount, handlers.replace(/\s+/g, ' '), auth]);
  }

  const directPattern = /app\.(get|post|put|patch|delete)\(\s*['`]([^'`]+)['`]\s*,\s*([^\n;]+?)(?:async\s*)?\(/g;
  for (const match of source.matchAll(directPattern)) {
    const method = match[1].toUpperCase();
    const route = match[2];
    const handlers = match[3].trim();
    rows.push([`${method} ${route}`, handlers.replace(/\s+/g, ' '), handlers.includes('authenticate') ? 'direct-auth' : 'public/unknown']);
  }
  return rows.sort((a, b) => a[0].localeCompare(b[0]));
}

function routeFiles() {
  const rows = [];
  for (const file of [...list('backend/routes', '.ts'), 'backend/middleware/auth.ts']) {
    const source = read(file);
    const methods = [...source.matchAll(/router\.(get|post|put|patch|delete|use)\(\s*['`]([^'`]+)['`]?/g)]
      .map((match) => `${match[1].toUpperCase()} ${match[2]}`);
    const authRefs = [...new Set([...source.matchAll(/\b(authenticate|authenticateEmbedded|authorize|authorizeClientAccess|optionalAuth|requireDeviceAuth|verifyShopifyWebhook|validateApiKey)\b/g)].map((m) => m[1]))];
    const directSqlCount = (source.match(/\bpool\.query\s*\(/g) || []).length;
    const sideEffects = [
      source.includes('queue') || source.includes('QueueNames') ? 'queue' : '',
      source.includes('shopify') || source.includes('Shopify') ? 'shopify' : '',
      source.includes('publish') || source.includes('Publish') ? 'publish' : '',
      source.includes('exec') || source.includes('spawn') ? 'shell' : '',
    ].filter(Boolean).join(', ');
    rows.push([file, methods.length, methods.slice(0, 8).join('<br>'), authRefs.join(', ') || 'none detected', directSqlCount, sideEffects || 'none detected']);
  }
  return rows;
}

function roles() {
  const schema = read('backend/database/schema.sql');
  const types = read('backend/types/index.ts');
  const auth = read('backend/middleware/auth.ts');
  const frontend = read('frontend/src/types/index.ts');
  const roleSet = new Set();
  for (const source of [schema, types, auth, frontend]) {
    for (const match of source.matchAll(/'([a-z_]+)'/g)) {
      if (['super_admin', 'admin', 'editor', 'client', 'connector'].includes(match[1])) roleSet.add(match[1]);
    }
  }
  return [...roleSet].sort().map((role) => [
    role,
    types.includes(`'${role}'`) ? 'yes' : 'no',
    schema.includes(`'${role}'`) ? 'yes' : 'no',
    frontend.includes(`'${role}'`) ? 'yes' : 'no',
    role === 'connector' ? 'API key synthetic user in backend/middleware/auth.ts' : '',
  ]);
}

function tables() {
  const files = ['backend/database/schema.sql', ...list('backend/database', '.sql').filter((file) => file.includes('migration_'))];
  const tableMap = new Map();
  const ensureTable = (tableName) => {
    if (!tableMap.has(tableName)) {
      tableMap.set(tableName, { files: [], hasClientId: false, sensitiveColumns: new Set() });
    }
    return tableMap.get(tableName);
  };

  for (const file of files) {
    const source = read(file);
    for (const match of source.matchAll(/CREATE TABLE IF NOT EXISTS\s+([a-zA-Z0-9_]+)/g)) {
      const tableName = match[1];
      const start = match.index;
      const end = source.indexOf(');', start);
      const body = end > start ? source.slice(start, end) : '';
      const existing = ensureTable(tableName);
      existing.files.push(file);
      existing.hasClientId ||= /\bclient_id\b/.test(body);
      for (const column of body.matchAll(/^\s*([a-zA-Z0-9_]+)\s+/gm)) {
        if (isSensitiveIdentifier(column[1])) existing.sensitiveColumns.add(column[1]);
      }
    }
    for (const match of source.matchAll(/ALTER TABLE\s+([a-zA-Z0-9_]+)\s+ADD COLUMN(?: IF NOT EXISTS)?\s+([a-zA-Z0-9_]+)/gi)) {
      const existing = ensureTable(match[1]);
      if (!existing.files.includes(file)) existing.files.push(file);
      existing.hasClientId ||= match[2] === 'client_id';
      if (isSensitiveIdentifier(match[2])) existing.sensitiveColumns.add(match[2]);
    }
  }

  return [...tableMap.entries()].sort(([a], [b]) => a.localeCompare(b)).map(([name, info]) => [
    name,
    info.hasClientId ? 'tenant/client-owned' : 'global/system or join-owned',
    info.sensitiveColumns.size > 0 ? `contains sensitive fields: ${[...info.sensitiveColumns].sort().join(', ')}` : '',
    info.files.join('<br>'),
  ]);
}

function queuesAndWorkflows() {
  const queueSource = read('backend/utils/queue.ts');
  const rows = [...queueSource.matchAll(/([A-Z0-9_]+)\s*=\s*'([^']+)'/g)].map((match) => [match[1], match[2], 'BullMQ QueueNames']);
  const schema = read('backend/database/schema.sql');
  for (const tableName of ['jobs', 'publishing_queue', 'schedules', 'workflow_logs', 'activity_logs']) {
    if (schema.includes(`CREATE TABLE IF NOT EXISTS ${tableName}`)) rows.push([tableName, tableName, 'SQL workflow/state table']);
  }
  return rows.sort((a, b) => a[1].localeCompare(b[1]));
}

function integrations() {
  const envNames = new Set();
  const files = [
    '.env.example',
    'docker-compose.yml',
    'docker-compose.sidecars.yml',
    ...walk('backend', ['.ts']),
    ...walk('deploy', ['.sh', '.yml', '.yaml', '.example']),
    ...walk('docker', ['.yml', '.yaml']),
    ...walk('frontend', ['.example']),
    ...walk('scripts', ['.js', '.mjs', '.ts', '.sh']),
    ...walk('.github/workflows', ['.yml', '.yaml']),
  ];
  for (const file of files) {
    if (!fs.existsSync(path.join(ROOT, file))) continue;
    const source = read(file);
    for (const match of source.matchAll(/process\.env\.([A-Z0-9_]+)/g)) envNames.add(match[1]);
    for (const match of source.matchAll(/^\s*(?:export\s+)?([A-Z][A-Z0-9_]{2,})\s*=/gm)) envNames.add(match[1]);
    for (const match of source.matchAll(/\$\{?([A-Z][A-Z0-9_]{2,})\}?/g)) envNames.add(match[1]);
  }
  return [...envNames].sort().map((name) => {
    const secretLike = isSensitiveIdentifier(name);
    let owner = 'Operations Manager';
    if (/SHOPIFY/.test(name)) owner = 'Integration Manager / Publishing Manager';
    if (/GOOGLE|GSC|META|SERP|DATAFORSEO|PEXELS/.test(name)) owner = 'Integration Manager';
    if (/OPENAI|OLLAMA|LLM|AI/.test(name)) owner = 'Intelligence Manager';
    if (/DB|POSTGRES|REDIS|BACKUP|LOG/.test(name)) owner = 'Storage Manager / Operations Manager';
    return [name, owner, secretLike ? 'secret/config-sensitive' : 'config'];
  });
}

function main() {
  ensureOutDir();
  writeDoc('ROUTE-AUTH-MATRIX.md', 'Route And Auth Matrix', [
    '## Express Mounts',
    table(['Mount or direct route', 'Handlers', 'Auth classification'], routeMounts()),
    '',
    '## Route File Scan',
    table(['File', 'Route count', 'First routes', 'Auth references', 'Direct SQL calls', 'Side-effect hints'], routeFiles()),
  ]);
  writeDoc('ROLE-ACTION-MATRIX.md', 'Role And Action Matrix', [
    '## Source-Detected Roles',
    table(['Role', 'Backend type', 'Database role check', 'Frontend type', 'Notes'], roles()),
  ]);
  writeDoc('STORAGE-OWNERSHIP.md', 'Storage Ownership Matrix', [
    '## Tables',
    table(['Table', 'Ownership classification', 'Sensitivity hint', 'Source files'], tables()),
  ]);
  writeDoc('JOB-WORKFLOW-MATRIX.md', 'Job And Workflow Matrix', [
    '## Queues And Workflow Stores',
    table(['Name', 'Runtime identifier', 'Source'], queuesAndWorkflows()),
    '',
    '## Current Contract',
    '- BullMQ queues are the active execution mechanism in `backend/utils/queue.ts`.',
    '- SQL `jobs`, `publishing_queue`, `schedules`, `workflow_logs`, and `activity_logs` are state/history stores but are not yet reconciled into one durable workflow lifecycle.',
    '- Phase 3 must define the canonical workflow/outbox before managers trigger automatic cross-system effects.',
  ]);
  writeDoc('INTEGRATION-CREDENTIAL-MATRIX.md', 'Integration Credential Matrix', [
    '## Environment Contracts',
    table(['Environment name', 'Owner', 'Classification'], integrations()),
    '',
    '## Current Contract',
    '- Secret values must stay in environment/secret stores or credential vaults, never in docs or source.',
    '- Legacy plaintext token stores must be treated as compatibility surfaces until a token migration is designed and verified.',
  ]);
  console.log(`Architecture contracts generated in ${path.relative(ROOT, OUT_DIR)}`);
}

main();
